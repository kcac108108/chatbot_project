# 테이블명마다 붙여 운영/로컬 양쪽에서 동일 쿼리로 동작하게 한다.
from app.core.config import DB_TABLE_SUFFIX as _SFX

MENU1_QUERY = f"""
SELECT A.ORGANIZATION_ID, A.CRP_NO, A.CRP_NAME, A.CRP_DEPT_NAME,
       A.BUSINESS_NAME, A.LAW_COMMENT, A.SUPPORT_COMMENT, A.CRP_GBN, A.CONTENT,
       B.DETAIL_ID, B.REQ_DTM, B.TRNS_MTD, B.STS_ISSUE_TYPE, B.STS_ISSUE_GBN,
       B.STS_ISSUE_ITEM, B.TRNS_CYCLE, B.REQ_NOTE, B.REQ_GBN, B.PAY_AMT,
       CO.ORG_ATT_CNT, CO.ORG_ATT_NAMES,
       CH.DTL_ATT_CNT, CH.DTL_ATT_NAMES
  FROM HISTORY_ORGANIZATION_INFO{_SFX} A,
       HISTORY_ORGANIZATION_DETAIL{_SFX} B,
       ( SELECT ATTFILE_ID, COUNT(*) AS ORG_ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS ORG_ATT_NAMES,
                MAX(IN_DTM) AS ORG_ATT_IN_DTM, MAX(CR_DTM) AS ORG_ATT_CR_DTM
           FROM TM_ATTFILE{_SFX} WHERE DOCUCD = 'C0002010' GROUP BY ATTFILE_ID ) CO,
       ( SELECT ATTFILE_ID, COUNT(*) AS DTL_ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS DTL_ATT_NAMES,
                MAX(IN_DTM) AS DTL_ATT_IN_DTM, MAX(CR_DTM) AS DTL_ATT_CR_DTM
           FROM TM_ATTFILE{_SFX} WHERE DOCUCD = 'C0002011' GROUP BY ATTFILE_ID ) CH
 WHERE 1=1
   AND A.ORGANIZATION_ID = B.ORGANIZATION_ID(+)
   AND A.ORGANIZATION_ID = CO.ATTFILE_ID(+)
   AND B.DETAIL_ID = CH.ATTFILE_ID(+)
   AND (:since IS NULL OR A.IN_DTM > :since OR A.CR_DTM > :since OR B.IN_DTM > :since OR B.CR_DTM > :since
        OR CO.ORG_ATT_IN_DTM > :since OR CO.ORG_ATT_CR_DTM > :since
        OR CH.DTL_ATT_IN_DTM > :since OR CH.DTL_ATT_CR_DTM > :since)
 ORDER BY A.CR_DTM DESC, B.REQ_DTM DESC
"""

