doc = Document()

# 기본 폰트를 맑은 고딕으로 설정
style = doc.styles["Normal"]
style.font.name = "맑은 고딕"
style.font.size = Pt(10.5)
rpr = style.element.get_or_add_rPr()
rFonts = rpr.find(qn("w:rFonts"))
if rFonts is None:
    rFonts = rpr.makeelement(qn("w:rFonts"), {})
    rpr.append(rFonts)
rFonts.set(qn("w:eastAsia"), "맑은 고딕")

def set_korean_font(run, size=None, bold=None, color=None):
    run.font.name = "맑은 고딕"
    rpr = run._element.get_or_add_rPr()
    rFonts = rpr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rFonts)
    rFonts.set(qn("w:eastAsia"), "맑은 고딕")
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)

def h1(text):
    p = doc.add_heading(level=1)
    r = p.add_run(text)
    set_korean_font(r, size=20, bold=True)

def h2(text):
    p = doc.add_heading(level=2)
    r = p.add_run(text)
    set_korean_font(r, size=14, bold=True)
    return p

def h3(text):
    p = doc.add_heading(level=3)
    r = p.add_run(text)
    set_korean_font(r, size=12, bold=True)
    return p

def para(text, bold=False, indent=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_korean_font(r, size=10.5, bold=bold)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.space_after = Pt(6)
    return p

def bullet(text, level=0):
    p = doc.add_paragraph(style="List Bullet" if level == 0 else "List Bullet 2")
    r = p.add_run(text)
    set_korean_font(r, size=10.5)
    p.paragraph_format.space_after = Pt(3)
    return p

def numbered(text):
    p = doc.add_paragraph(style="List Number")
    r = p.add_run(text)
    set_korean_font(r, size=10.5)
    p.paragraph_format.space_after = Pt(3)
    return p

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    hdr_cells = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr_cells[i].text = ""
        r = hdr_cells[i].paragraphs[0].add_run(htext)
        set_korean_font(r, size=10, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(val))
            set_korean_font(r, size=9.5)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t

def caption(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_korean_font(r, size=9.5, bold=True, color=(90, 90, 90))
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)

def image(filename, width_cm=15.5):
    path = os.path.join(SHOT, filename)
    doc.add_picture(path, width=Cm(width_cm))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph().paragraph_format.space_after = Pt(10)

def page_break():
    doc.add_page_break()

