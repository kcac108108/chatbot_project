PROMPT 3.4 메뉴 4: 심의위원회 (메인+첨부)
PROMPT ============================================================
COL CRP_NAME FORMAT A16
COL DISCUSSION_RESULT FORMAT A16
COL ATT_NAMES FORMAT A25 TRUNC
SELECT A.DISCUSSION_ID, A.CRP_NAME, A.YEAR, A.SEQ, A.DISCUSSION_RESULT,
       CO.ATT_CNT, CO.ATT_NAMES
  FROM HISTORY_DISCUSSION_COMMITTEE A,
       ( SELECT ATTFILE_ID, COUNT(*) AS ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS ATT_NAMES
           FROM TM_ATTFILE WHERE DOCUCD = 'C0002013' GROUP BY ATTFILE_ID ) CO
 WHERE A.DISCUSSION_ID = CO.ATTFILE_ID(+)
 ORDER BY A.YEAR DESC, A.SEQ DESC
 FETCH FIRST 8 ROWS ONLY;

SELECT COUNT(*) AS 결과행수, MAX(CO.ATT_CNT) AS 최대첨부수
  FROM HISTORY_DISCUSSION_COMMITTEE A,
       ( SELECT ATTFILE_ID, COUNT(*) AS ATT_CNT FROM TM_ATTFILE WHERE DOCUCD = 'C0002013' GROUP BY ATTFILE_ID ) CO
 WHERE A.DISCUSSION_ID = CO.ATTFILE_ID(+);
