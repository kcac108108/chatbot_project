PROMPT 3.2 메뉴 2: 외부요청 (메인+첨부)
PROMPT ============================================================
COL CRP_NAME FORMAT A16
COL ATT_NAMES FORMAT A25 TRUNC
SELECT A.REQUEST_ID, A.CRP_NAME, A.REQ_PERSON_NAME, A.PROC_PERSON_NAME,
       CO.ATT_CNT, CO.ATT_NAMES
  FROM HISTORY_EXTERNAL_REQUEST A,
       ( SELECT ATTFILE_ID, COUNT(*) AS ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS ATT_NAMES
           FROM TM_ATTFILE WHERE DOCUCD = 'C0002012' GROUP BY ATTFILE_ID ) CO
 WHERE A.REQUEST_ID = CO.ATTFILE_ID(+)
 ORDER BY A.REQUEST_ID;

