PROMPT 3.1 메뉴 1: 기관별 사업정보 (메인+이력+첨부x2)
PROMPT ============================================================
SELECT COUNT(*) AS 결과행수
  FROM HISTORY_ORGANIZATION_INFO A,
       HISTORY_ORGANIZATION_DETAIL B,
       ( SELECT ATTFILE_ID, COUNT(*) AS ORG_ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS ORG_ATT_NAMES
           FROM TM_ATTFILE WHERE DOCUCD = 'C0002010' GROUP BY ATTFILE_ID ) CO,
       ( SELECT ATTFILE_ID, COUNT(*) AS DTL_ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS DTL_ATT_NAMES
           FROM TM_ATTFILE WHERE DOCUCD = 'C0002011' GROUP BY ATTFILE_ID ) CH
 WHERE 1=1
   AND A.ORGANIZATION_ID = B.ORGANIZATION_ID(+)
   AND A.ORGANIZATION_ID = CO.ATTFILE_ID(+)
   AND B.DETAIL_ID = CH.ATTFILE_ID(+);

COL CRP_NAME FORMAT A16
COL DETAIL_ID FORMAT A12
COL ORG_ATT_NAMES FORMAT A25 TRUNC
COL DTL_ATT_NAMES FORMAT A25 TRUNC
SELECT A.ORGANIZATION_ID, A.CRP_NAME, B.DETAIL_ID,
       CO.ORG_ATT_CNT, CO.ORG_ATT_NAMES, CH.DTL_ATT_CNT, CH.DTL_ATT_NAMES
  FROM HISTORY_ORGANIZATION_INFO A,
       HISTORY_ORGANIZATION_DETAIL B,
       ( SELECT ATTFILE_ID, COUNT(*) AS ORG_ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS ORG_ATT_NAMES
           FROM TM_ATTFILE WHERE DOCUCD = 'C0002010' GROUP BY ATTFILE_ID ) CO,
       ( SELECT ATTFILE_ID, COUNT(*) AS DTL_ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS DTL_ATT_NAMES
           FROM TM_ATTFILE WHERE DOCUCD = 'C0002011' GROUP BY ATTFILE_ID ) CH
 WHERE 1=1
   AND A.ORGANIZATION_ID = B.ORGANIZATION_ID(+)
   AND A.ORGANIZATION_ID = CO.ATTFILE_ID(+)
   AND B.DETAIL_ID = CH.ATTFILE_ID(+)
 ORDER BY A.ORGANIZATION_ID
 FETCH FIRST 8 ROWS ONLY;

PROMPT --- 케이스별 검증: 기관당 이력수/첨부수 분포 ---
SELECT CASE
         WHEN A.ORGANIZATION_ID BETWEEN 'ORG0000001' AND 'ORG0000025' THEN '①메인만'
         WHEN A.ORGANIZATION_ID BETWEEN 'ORG0000026' AND 'ORG0000050' THEN '②메인+메인첨부'
         WHEN A.ORGANIZATION_ID BETWEEN 'ORG0000051' AND 'ORG0000075' THEN '③메인+이력+이력첨부'
         ELSE '④전부'
       END AS 케이스,
       COUNT(DISTINCT A.ORGANIZATION_ID) AS 기관수,
       COUNT(B.DETAIL_ID) AS 이력수,
       SUM(CASE WHEN CO.ORG_ATT_CNT IS NOT NULL THEN 1 ELSE 0 END) AS 메인첨부있는기관행수,
       SUM(CASE WHEN CH.DTL_ATT_CNT IS NOT NULL THEN 1 ELSE 0 END) AS 이력첨부있는이력행수
  FROM HISTORY_ORGANIZATION_INFO A,
       HISTORY_ORGANIZATION_DETAIL B,
       ( SELECT ATTFILE_ID, COUNT(*) AS ORG_ATT_CNT FROM TM_ATTFILE WHERE DOCUCD = 'C0002010' GROUP BY ATTFILE_ID ) CO,
       ( SELECT ATTFILE_ID, COUNT(*) AS DTL_ATT_CNT FROM TM_ATTFILE WHERE DOCUCD = 'C0002011' GROUP BY ATTFILE_ID ) CH
 WHERE 1=1
   AND A.ORGANIZATION_ID = B.ORGANIZATION_ID(+)
   AND A.ORGANIZATION_ID = CO.ATTFILE_ID(+)
   AND B.DETAIL_ID = CH.ATTFILE_ID(+)
 GROUP BY CASE
         WHEN A.ORGANIZATION_ID BETWEEN 'ORG0000001' AND 'ORG0000025' THEN '①메인만'
         WHEN A.ORGANIZATION_ID BETWEEN 'ORG0000026' AND 'ORG0000050' THEN '②메인+메인첨부'
         WHEN A.ORGANIZATION_ID BETWEEN 'ORG0000051' AND 'ORG0000075' THEN '③메인+이력+이력첨부'
         ELSE '④전부'
       END
 ORDER BY 1;

