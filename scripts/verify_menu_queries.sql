PROMPT 3.3 메뉴 3: 내부자료 (게시판형: 글+댓글, 댓글별 첨부)
PROMPT ============================================================
COL TITLE FORMAT A20
COL FILE_COMMENT FORMAT A20 TRUNC
COL ATT_NAMES FORMAT A20 TRUNC
SELECT A.REQUEST_ID, A.TITLE, A.USERNM, A.DECIDING_OFFICER,
       B.IN_USERID, B.CR_DTM AS DTL_CR_DTM, B.FILE_COMMENT,
       CO.ATT_CNT, CO.ATT_NAMES
  FROM HISTORY_INTERNAL_INFO A,
       HISTORY_INTERNAL_DETAIL B,
       ( SELECT ATTFILE_ID, ATTFILE_NUM, COUNT(*) AS ATT_CNT,
                LISTAGG(ATTFILE_NM, ', ') WITHIN GROUP (ORDER BY ATTFILE_NM) AS ATT_NAMES
           FROM TM_ATTFILE WHERE DOCUCD = 'C0002014'
          GROUP BY ATTFILE_ID, ATTFILE_NUM ) CO
 WHERE 1=1
   AND A.REQUEST_ID = B.REQUEST_ID(+)
   AND B.REQUEST_ID = CO.ATTFILE_ID(+)
   AND B.ATTFILE_NUM = CO.ATTFILE_NUM(+)
 ORDER BY A.REQUEST_ID, B.CR_DTM;

